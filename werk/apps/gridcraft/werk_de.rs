//! Werkbank: German interface texts for GridCraft.
//!
//! `i18n::de::translate` looks here first, so these entries complete the upstream German catalog
//! (every text the other languages already translate) and give it Swiss spelling (ss for ß).
//! [`t`], [`ts`] and [`field`] translate texts that the upstream UI draws without `tr()`; they
//! follow the language of the frame being drawn, which `i18n::set_current` hands to [`set`].
//! Function names and formulas are never translated.

use std::cell::Cell;

use crate::i18n::Language;

thread_local! {
    static LANGUAGE: Cell<Language> = const { Cell::new(Language::En) };
}

/// Remembers the language of the frame being drawn (called by `i18n::set_current`).
pub fn set(language: Language) {
    LANGUAGE.with(|current| current.set(language));
}

fn current() -> Language {
    LANGUAGE.with(Cell::get)
}

/// Translates an interface text for the frame's language; unknown text is returned unchanged.
pub fn t(text: &str) -> &str {
    // `Language::tr` reads `context|label` keys; a plain text that contains `|` stays as it is.
    if text.contains('|') { text } else { current().tr(text) }
}

/// [`t`] for texts held in a `String` (messages, notices).
pub fn ts(text: &str) -> String {
    t(text).to_string()
}

/// Translates the labels of a dialog field for drawing; keys and values stay unchanged.
#[allow(unreachable_patterns)] // `other` keeps this compiling if upstream adds a field kind.
pub fn field(f: crate::dialogs::Field) -> crate::dialogs::Field {
    use crate::dialogs::Field;
    match f {
        Field::Text { key, label } => Field::Text { key, label: t(label) },
        Field::Password { key, label } => Field::Password { key, label: t(label) },
        Field::Number { key, label } => Field::Number { key, label: t(label) },
        Field::Choice { key, label, options } => {
            Field::Choice { key, label: t(label), options: options.into_iter().map(|(value, text)| (value, t(text))).collect() }
        }
        Field::Check { key, label } => Field::Check { key, label: t(label) },
        Field::Note(text) => Field::Note(ts(&text)),
        other => other,
    }
}

