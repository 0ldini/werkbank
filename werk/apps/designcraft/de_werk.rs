#[cfg(test)]
mod tests {
    use super::TABLE;

    fn placeholders(text: &str) -> Vec<&str> {
        let mut found: Vec<&str> = text.match_indices('{').filter_map(|(i, _)| text[i..].find('}').map(|len| &text[i..i + len + 1])).collect();
        found.sort_unstable();
        found
    }

    #[test]
    fn rows_are_unique_nonempty_and_keep_placeholders() {
        let mut seen = std::collections::HashSet::new();
        for (en, de) in TABLE {
            assert!(seen.insert(*en), "duplicate {en}");
            assert!(!de.is_empty(), "{en}");
            assert_eq!(placeholders(en), placeholders(de), "placeholders of {en}");
            assert_eq!(en.trim_end().ends_with(':'), de.trim_end().ends_with(':'), "colon of {en}");
        }
    }
}
